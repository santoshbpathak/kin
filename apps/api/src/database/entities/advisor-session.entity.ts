/**
 * AdvisorSession — per-user state for the three-tier advisory connect
 * layer (Module B, PRD v1.4 §2).
 *
 * Tier semantics:
 *   1: KIN AI assistant (Tier 1, GPT-4o, the only one stored as a chat
 *      transcript here)
 *   2: Human advisor chat
 *   3: Human advisor phone call
 *
 * Tier transitions are user-initiated. The `transcriptSharedConsent`
 * flag records whether the user agreed to share the Tier 1 transcript
 * with the Tier 2/3 advisor — if false, tier1Transcript must NOT be
 * exposed to advisor-facing endpoints.
 *
 * The `kinReport` snapshot is captured at session start so the Tier 1
 * agent's context is stable for the lifetime of the conversation, even
 * if the user re-runs their score in another tab.
 */

import {
  Entity, PrimaryGeneratedColumn, Column, CreateDateColumn, UpdateDateColumn, Index,
} from 'typeorm'
import { jsonColumnType, timestampColumnType } from './column-types'

export interface AdvisorSessionMessage {
  role: 'system' | 'user' | 'assistant'
  content: string
  ts: string
}

export interface AdvisorBriefBlob {
  line1: string
  line2: string
  line3: string
}

/**
 * Frozen snapshot of the user's KIN report at the time a Tier 1
 * conversation begins. Used both for context injection into the prompt
 * and for the advisor brief at upgrade time.
 */
export interface KinReportSnapshot {
  compositeScore: number
  lifeSubScore: number
  healthSubScore: number
  incomeSubScore: number
  lifeGapSummary: string
  healthGapSummary: string
  incomeGapSummary: string
  topRecommendation: string
  recommendations: Array<{
    type: string
    title: string
    basisText: string
  }>
  hiddenCoverages: string[]
  estimatedFields: string[]
  unknownFields: string[]
}

@Entity('advisor_sessions')
export class AdvisorSession {
  @PrimaryGeneratedColumn('uuid')
  advisorSessionId: string

  @Index('idx_advisor_session_user')
  @Column({ type: 'uuid' })
  userId: string

  @Column({ type: 'varchar', length: 512, nullable: true })
  sessionToken: string | null

  @Column({ type: 'int', default: 1 })
  currentTier: 1 | 2 | 3

  /**
   * Full Tier-1 chat history. Always written here; access from advisor-
   * facing endpoints is gated by transcriptSharedConsent.
   */
  @Column({ type: jsonColumnType, default: () => "'[]'" })
  tier1Transcript: AdvisorSessionMessage[]

  /**
   * The KIN report snapshot captured when the Tier 1 conversation begins.
   * Drives the agent's system prompt and the advisor pre-brief.
   */
  @Column({ type: jsonColumnType, nullable: true })
  kinReport: KinReportSnapshot | null

  /** Generated by AdvisorBriefService when the user upgrades to Tier 2/3. */
  @Column({ type: jsonColumnType, nullable: true })
  advisorBrief: AdvisorBriefBlob | null

  /** Stays null until a human advisor is assigned (Tier 2). */
  @Column({ type: 'varchar', length: 36, nullable: true })
  advisorId: string | null

  @Column({ type: 'boolean', default: false })
  transcriptSharedConsent: boolean

  @Column({ type: timestampColumnType, nullable: true })
  tierUpgradedAt: Date | null

  @Column({ type: 'int', default: 0 })
  turnCount: number

  @CreateDateColumn()
  createdAt: Date

  @UpdateDateColumn()
  updatedAt: Date
}
